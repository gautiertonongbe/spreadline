def listing_upc(fixture: FixtureProduct, listing: FixtureListing) -> str | None:
    if not listing.has_upc:
        return None
    return listing.upc or fixture.upc


def deterministic_unit(*parts: object) -> float:
    """A stable pseudo-random float in [0, 1) for the given key parts.

    Seeded by content rather than by a PRNG's global state, so the same fixture
    produces the same history on every process, machine and test run. Reproducible
    fixtures are the difference between a failing test that means something and a
    flaky one.
    """
    digest = hashlib.sha256("|".join(str(part) for part in parts).encode()).digest()
    return int.from_bytes(digest[:8], "big") / float(1 << 64)
