"""Fixture catalogue behind MockProvider.

Thirty-two products chosen to exercise the decisions the platform has to get
right, not to look good in a demo. Roughly a third are traps: false matches,
pack and size mismatches, a price that is low because the listing is about to go
out of stock, a product with three price observations pretending to be a trend.

Every UPC here is check-digit valid, computed at import rather than typed, so the
identity engine is exercised against real identifiers.

Nothing in this module is market data. MockProvider reports ``is_live = False``
and the API surfaces that flag on every response built from it.
"""

from __future__ import annotations

import hashlib
