from app.domains.identity.normalization import gtin_check_digit
from app.models.enums import Availability, Marketplace


def _upc(base11: str) -> str:
    """Complete an 11-digit body into a valid UPC-A."""
    if len(base11) != 11 or not base11.isdigit():
        raise ValueError(f"UPC body must be 11 digits: {base11!r}")
    return base11 + str(gtin_check_digit(base11))


@dataclass(frozen=True)
class FixtureListing:
    marketplace: Marketplace
    external_id: str
    title: str
    price: Decimal
    shipping: Decimal = Decimal("0")
    availability: Availability = Availability.IN_STOCK
    seller_count: int | None = 3
    offer_count: int | None = 4
    sales_rank: int | None = None
    rank_category: str | None = None
    review_count: int | None = None
    rating: Decimal | None = None
    quantity_available: int | None = None
    #: Overrides the product's UPC. None keeps the shared identifier; a distinct
    #: value is how a trap listing is made to look similar but identify differently.
    upc: str | None = None
    #: When False the listing carries no GTIN at all, forcing the matcher down to
    #: weaker evidence.
    has_upc: bool = True
    mpn: str | None = None
    condition: str = "new"
    pack_count: int | None = None
    attributes: dict[str, str] = field(default_factory=dict)
    #: Number of days of price history available. Small values are deliberate.
    history_days: int = 180
    #: Daily volatility as a share of price.
    volatility: Decimal = Decimal("0.04")
    #: Total drift across the window, as a share of price.
    trend: Decimal = Decimal("0")
    #: Applied to the most recent observation only, to stage an anomaly.
    latest_shock: Decimal = Decimal("0")
    #: Seller count at the start of the window, for competition trend.
    seller_count_start: int | None = None
    demand_available: bool = True


@dataclass(frozen=True)
class FixtureProduct:
    key: str
    brand: str
    category: str
    upc: str
    weight_lb: Decimal
    listings: tuple[FixtureListing, ...]
    #: What this fixture is here to test. Shown in the seeded data so a failing
    #: expectation is traceable to intent.
    scenario: str
    expectation: str
    mpn: str | None = None
    model: str | None = None
    cubic_feet: Decimal | None = None

    def listing(self, marketplace: Marketplace) -> FixtureListing | None:
        return next((item for item in self.listings if item.marketplace is marketplace), None)


